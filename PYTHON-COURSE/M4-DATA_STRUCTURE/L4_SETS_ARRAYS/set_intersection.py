setx = {"green", "blue","red","orange"}
sety = {"blue", "yellow","red","brown"}
print("Original set elements:")
print(setx)
print(sety)
print("\nIntersection of two said sets:")
setz = setx.intersection(sety)
setp = setx.symmetric_difference(sety)
print(setz)
print("\nunion of two said sets:")
print(setp)