import numpy as np

# Creating a NumPy array
arr = np.array([10, 20, 30, 40, 50])

# Display original array
print("Original Array:", arr)

# Addition
print("Array after addition (+5):", arr + 5)

# Subtraction
print("Array after subtraction (-5):", arr - 5)

# Multiplication
print("Array after multiplication (*2):", arr * 2)

# Division
print("Array after division (/2):", arr / 2)

# Finding sum of elements
print("Sum of array elements:", np.sum(arr))

# Finding mean (average)
print("Mean of array:", np.mean(arr))

# Finding maximum and minimum value
print("Maximum value:", np.max(arr))
print("Minimum value:", np.min(arr))

# Square of array elements
print("Square of array elements:", np.square(arr))